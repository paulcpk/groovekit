// Generates TypeScript types and C++ structs (with strict, path-aware readers) from the JSON Schemas.
// Usage: node codegen/generate.ts [--check]
//
// Supports the subset of JSON Schema the GrooveKit schemas use: objects with properties,
// primitive aliases in $defs, string and integer enums, arrays, string-keyed maps
// (additionalProperties), free-form values ({} or an object without properties), const
// tags, and oneOf unions discriminated by a const property. $refs may point into
// another schema file ("project.schema.json#/$defs/Channel"); definition names are
// unique across files.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

type Schema = Record<string, any>;

const schemaDir = join(dirname(fileURLToPath(import.meta.url)), "..");

const targets = [
  { schema: "project.schema.json", ts: "generated/project.ts", cpp: "../engine/src/model/Project.generated.h" },
  { schema: "protocol.schema.json", ts: "generated/protocol.ts", cpp: "../engine/src/model/Protocol.generated.h" },
];

const banner = (source: string) => `Generated by schema/codegen/generate.ts from schema/${source}. Do not edit.`;

//==============================================================================
function capitalise(s: string): string {
  return s[0].toUpperCase() + s.slice(1);
}

const quote = (s: string) => JSON.stringify(s);

const constraintKeys = ["minimum", "maximum", "pattern", "minLength", "minItems", "enum"] as const;

type DefKind = "alias" | "struct" | "union" | "any";

type Definition = { name: string; file: string; schema: Schema };

type Resolved = {
  name: string; // the named type, or a structural description for arrays and maps
  kind: "primitive" | "struct" | "union" | "enum" | "array" | "map" | "any";
  schema: Schema; // effective schema, with alias constraints merged in
  item?: Resolved;
};

/** Every definition across the schema files, plus the shared rules for interpreting them. */
class SchemaSet {
  readonly defs = new Map<string, Definition>();
  readonly enums = new Map<string, { file: string; values: string[] }>();
  readonly roots = new Map<string, Schema>();

  constructor(files: string[]) {
    for (const file of files) {
      const root = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
      this.roots.set(file, root);

      for (const [name, schema] of Object.entries<Schema>(root.$defs ?? {})) this.add({ name, file, schema });

      if (root.type === "object") this.add({ name: root.title, file, schema: root });
    }

    for (const def of this.defs.values())
      if (this.kind(def.name) === "struct")
        for (const [prop, s] of Object.entries<Schema>(def.schema.properties ?? {}))
          if (s.type === "string" && s.enum) this.enums.set(this.enumName(def.name, prop), { file: def.file, values: s.enum });
  }

  add(def: Definition) {
    if (this.defs.has(def.name)) throw new Error(`Duplicate definition ${def.name}`);
    this.defs.set(def.name, def);
  }

  refName(ref: string): string {
    const match = /^(?:[\w.-]+\.json)?#\/\$defs\/(\w+)$/.exec(ref);
    if (!match || !this.defs.has(match[1])) throw new Error(`Unsupported or unknown $ref ${ref}`);
    return match[1];
  }

  def(name: string): Schema {
    return this.defs.get(name)!.schema;
  }

  kind(name: string): DefKind {
    const d = this.def(name);
    if (d.oneOf) return "union";
    if (d.type === "object" && d.properties) return "struct";
    if (isAny(d)) return "any";
    if (["string", "integer", "number", "boolean"].includes(d.type) && !(d.type === "string" && d.enum)) return "alias";
    throw new Error(`Unsupported definition ${name}`);
  }

  enumName(owner: string, prop: string): string {
    return owner + capitalise(prop);
  }

  resolve(s: Schema, owner: string, prop: string): Resolved {
    if (s.$ref) {
      const name = this.refName(s.$ref);
      const kind = this.kind(name);

      if (kind === "alias") {
        const merged: Schema = { ...this.def(name) };
        for (const k of constraintKeys) if (s[k] !== undefined) merged[k] = s[k];
        if (s.default !== undefined) merged.default = s.default;
        return { name, kind: "primitive", schema: merged };
      }

      return { name, kind: kind === "any" ? "any" : kind, schema: { ...this.def(name), ...s } };
    }
    if (isAny(s)) return { name: "any", kind: "any", schema: s };
    if (s.type === "string" && s.enum) return { name: this.enumName(owner, prop), kind: "enum", schema: s };
    if (s.type === "array") return { name: "array", kind: "array", schema: s, item: this.resolve(s.items, owner, prop) };
    if (s.type === "object" && s.additionalProperties)
      return { name: "map", kind: "map", schema: s, item: this.resolve(s.additionalProperties, owner, prop) };
    return { name: s.type, kind: "primitive", schema: s };
  }

  /** A struct whose fields all have defaults can be omitted from a document without becoming optional. */
  isDefaultable(name: string): boolean {
    if (this.kind(name) !== "struct") return false;
    const def = this.def(name);
    return (
      !def.required?.length &&
      Object.values<Schema>(def.properties ?? {}).every(
        (p) => p.default !== undefined || (p.$ref && this.isDefaultable(this.refName(p.$ref)))
      )
    );
  }

  isOptional(def: Schema, prop: string, s: Schema): boolean {
    if (def.required?.includes(prop)) return false;
    if (s.default !== undefined) return false;
    if (s.$ref && this.isDefaultable(this.refName(s.$ref))) return false;
    if (s.$ref && this.def(this.refName(s.$ref)).default !== undefined) return false;
    return true;
  }

  dependencies(name: string): string[] {
    const deps = new Set<string>();
    const visit = (s: Schema) => {
      if (!s || typeof s !== "object") return;
      if (s.$ref) return void deps.add(this.refName(s.$ref));
      if (s.items) visit(s.items);
      if (s.additionalProperties && typeof s.additionalProperties === "object") visit(s.additionalProperties);
      for (const p of Object.values<Schema>(s.properties ?? {})) visit(p);
      for (const o of s.oneOf ?? []) visit(o);
    };
    const def = this.def(name);
    for (const p of Object.values<Schema>(def.properties ?? {})) visit(p);
    for (const o of def.oneOf ?? []) visit(o);
    return [...deps];
  }

  /** Definitions of one file, dependencies first. */
  ordered(file: string): string[] {
    const order: string[] = [];
    const state = new Map<string, "visiting" | "done">();
    const visit = (name: string) => {
      if (state.get(name) === "done") return;
      if (state.get(name) === "visiting") throw new Error(`Recursive definition ${name}`);
      state.set(name, "visiting");
      for (const d of this.dependencies(name)) visit(d);
      state.set(name, "done");
      if (this.defs.get(name)!.file === file) order.push(name);
    };
    for (const def of this.defs.values()) if (def.file === file) visit(def.name);
    return order;
  }

  unionAlternatives(name: string) {
    const def = this.def(name);
    const tag = def.discriminator?.propertyName;
    if (!tag) throw new Error(`Union ${name} needs a discriminator`);
    return {
      tag: tag as string,
      alternatives: def.oneOf.map((o: Schema) => {
        const alt = this.refName(o.$ref);
        const value = this.def(alt).properties?.[tag]?.const;
        if (typeof value !== "string") throw new Error(`${alt} needs a const "${tag}"`);
        return { alt, value: value as string };
      }) as { alt: string; value: string }[],
    };
  }
}

function isAny(s: Schema): boolean {
  const keys = Object.keys(s).filter((k) => k !== "description" && k !== "default");
  return keys.length === 0 || (s.type === "object" && !s.properties && !s.additionalProperties && keys.length === 1);
}

function comment(text: string | undefined, indent: string, style: "cpp" | "ts"): string {
  if (!text) return "";
  return style === "cpp" ? `${indent}/** ${text} */\n` : `${indent}/** ${text} */\n`;
}

