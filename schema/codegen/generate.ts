// Generates TypeScript types and C++ structs (with strict, path-aware readers) from the JSON Schemas.
// Usage: node codegen/generate.ts [--check]
//
// The C++ generator supports the subset of JSON Schema the GrooveKit schemas use:
// objects with properties, primitive aliases in $defs, string enums, integer enums,
// arrays, string-keyed maps (additionalProperties), const tags and oneOf unions
// discriminated by a "type" property.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

type Schema = Record<string, any>;

const schemaDir = join(dirname(fileURLToPath(import.meta.url)), "..");

const targets = [
  {
    schema: "project.schema.json",
    ts: "generated/project.ts",
    cpp: "../engine/src/model/Project.generated.h",
  },
];

const banner = (source: string) =>
  `Generated by schema/codegen/generate.ts from schema/${source}. Do not edit.`;

//==============================================================================
function refName(ref: string): string {
  const prefix = "#/$defs/";
  if (!ref.startsWith(prefix)) throw new Error(`Unsupported $ref ${ref}`);
  return ref.slice(prefix.length);
}

function capitalise(s: string): string {
  return s[0].toUpperCase() + s.slice(1);
}

function cppString(s: string): string {
  return JSON.stringify(s);
}

function cppNumber(n: number): string {
  return Number.isInteger(n) ? String(n) : String(n);
}

const constraintKeys = ["minimum", "maximum", "pattern", "minLength", "minItems", "enum"] as const;

type Resolved = {
  cppType: string;
  kind: "primitive" | "struct" | "union" | "enum" | "array" | "map";
  schema: Schema; // effective schema, constraints from aliases merged in
};

class CppGenerator {
  readonly defs: Record<string, Schema>;
  readonly rootName: string;
  readonly enums = new Map<string, string[]>(); // enum type name -> values
  readonly order: string[] = [];
  readonly source: string;

  constructor(root: Schema, source: string) {
    this.source = source;
    this.rootName = root.title;
    this.defs = { ...root.$defs, [this.rootName]: root };
    this.collectEnums();
    this.sortDefinitions();
  }

  defKind(name: string): "alias" | "struct" | "union" {
    const d = this.defs[name];
    if (!d) throw new Error(`Unknown definition ${name}`);
    if (d.oneOf) return "union";
    if (d.type === "object") return "struct";
    if (["string", "integer", "number", "boolean"].includes(d.type) && !(d.type === "string" && d.enum)) return "alias";
    throw new Error(`Unsupported definition ${name}`);
  }

  primitiveType(s: Schema): string {
    switch (s.type) {
      case "string": return "std::string";
      case "boolean": return "bool";
      case "number": return "double";
      case "integer": return s.maximum === undefined && !s.enum ? "int64_t" : "int";
    }
    throw new Error(`Unsupported primitive ${JSON.stringify(s)}`);
  }

  enumName(owner: string, prop: string): string {
    return owner + capitalise(prop);
  }

  collectEnums() {
    for (const [name, def] of Object.entries(this.defs)) {
      if (this.defKind(name) !== "struct") continue;
      for (const [prop, s] of Object.entries<Schema>(def.properties ?? {}))
        if (s.type === "string" && s.enum) this.enums.set(this.enumName(name, prop), s.enum);
    }
  }

  resolve(s: Schema, owner: string, prop: string): Resolved {
    if (s.$ref) {
      const name = refName(s.$ref);
      const kind = this.defKind(name);
      if (kind === "alias") {
        const merged: Schema = { ...this.defs[name] };
        for (const k of constraintKeys) if (s[k] !== undefined) merged[k] = s[k];
        if (s.default !== undefined) merged.default = s.default;
        return { cppType: name, kind: "primitive", schema: merged };
      }
      return { cppType: name, kind: kind === "struct" ? "struct" : "union", schema: { ...this.defs[name], ...s } };
    }
    if (s.type === "string" && s.enum) return { cppType: this.enumName(owner, prop), kind: "enum", schema: s };
    if (s.type === "array") {
      const item = this.resolve(s.items, owner, prop);
      return { cppType: `std::vector<${item.cppType}>`, kind: "array", schema: s };
    }
    if (s.type === "object" && s.additionalProperties && !s.properties) {
      const value = this.resolve(s.additionalProperties, owner, prop);
      return { cppType: `std::map<std::string, ${value.cppType}>`, kind: "map", schema: s };
    }
    return { cppType: this.primitiveType(s), kind: "primitive", schema: s };
  }

  /** A struct whose fields all have defaults can be omitted from a document without becoming optional. */
  isDefaultable(name: string): boolean {
    if (this.defKind(name) !== "struct") return false;
    const def = this.defs[name];
    return !(def.required?.length) && Object.values<Schema>(def.properties ?? {}).every(
      (p) => p.default !== undefined || (p.$ref && this.isDefaultable(refName(p.$ref)))
    );
  }

  dependencies(name: string): string[] {
    const deps = new Set<string>();
    const visit = (s: Schema) => {
      if (!s || typeof s !== "object") return;
      if (s.$ref) { deps.add(refName(s.$ref)); return; }
      if (s.items) visit(s.items);
      if (s.additionalProperties && typeof s.additionalProperties === "object") visit(s.additionalProperties);
      for (const p of Object.values<Schema>(s.properties ?? {})) visit(p);
      for (const o of s.oneOf ?? []) visit(o);
    };
    const def = this.defs[name];
    for (const p of Object.values<Schema>(def.properties ?? {})) visit(p);
    for (const o of def.oneOf ?? []) visit(o);
    return [...deps];
  }

  sortDefinitions() {
    const state = new Map<string, "visiting" | "done">();
    const visit = (name: string) => {
      if (state.get(name) === "done") return;
      if (state.get(name) === "visiting") throw new Error(`Recursive definition ${name}`);
      state.set(name, "visiting");
      for (const d of this.dependencies(name)) visit(d);
      state.set(name, "done");
      this.order.push(name);
    };
    for (const name of Object.keys(this.defs)) visit(name);
  }

  //==============================================================================
  memberDefault(r: Resolved): string {
    const d = r.schema.default;
    if (d === undefined) {
      if (r.kind === "primitive" && r.schema.type !== "string") return " {}";
      return "";
    }
    if (r.kind === "enum") return ` = ${r.cppType}::${d}`;
    if (Array.isArray(d) || (typeof d === "object" && d !== null)) {
      if (Object.keys(d).length > 0) throw new Error("Only empty array/object defaults are supported");
      return "";
    }
    if (typeof d === "string") return ` = ${cppString(d)}`;
    if (typeof d === "boolean") return ` = ${d}`;
    if (typeof d === "number") return ` = ${cppNumber(d)}`;
    throw new Error(`Unsupported default ${JSON.stringify(d)}`);
  }

  isOptional(def: Schema, prop: string, s: Schema): boolean {
    if (def.required?.includes(prop)) return false;
    if (s.default !== undefined) return false;
    if (s.$ref && this.isDefaultable(refName(s.$ref))) return false;
    if (s.$ref && this.defs[refName(s.$ref)].default !== undefined) return false;
    return true;
  }

  checks(r: Resolved, expr: string): string[] {
    const s = r.schema;
    const out: string[] = [];
    if (r.kind === "primitive") {
      if (s.type === "integer" && s.enum) out.push(`r.checkOneOf (${expr}, { ${s.enum.join(", ")} });`);
      if (s.minimum !== undefined) out.push(`r.checkMin (${expr}, ${cppNumber(s.minimum)});`);
      if (s.maximum !== undefined) out.push(`r.checkMax (${expr}, ${cppNumber(s.maximum)});`);
      if (s.minLength !== undefined) out.push(`r.checkMinLength (${expr}, ${s.minLength});`);
      if (s.pattern !== undefined) out.push(`r.checkPattern (${expr}, ${cppString(s.pattern)});`);
    }
    if (r.kind === "array" && s.minItems !== undefined) out.push(`r.checkMinItems (${expr}, ${s.minItems});`);
    return out;
  }

  comment(text: string | undefined, indent: string): string {
    return text ? `${indent}/** ${text} */\n` : "";
  }

  //==============================================================================
  generate(): string {
    let out = `// ${banner(this.source)}\n\n#pragma once\n\n#include "JsonIO.h"\n\n#include <variant>\n\nnamespace gk::model\n{\n\n`;

    for (const name of this.order)
      if (this.defKind(name) === "alias")
        out += `${this.comment(this.defs[name].description, "")}using ${name} = ${this.primitiveType(this.defs[name])};\n`;

    for (const [name, values] of this.enums) {
      out += `\nenum class ${name}\n{\n${values.map((v) => `    ${v}`).join(",\n")}\n};\n`;
      out += `\ninline const char* toString (${name} v)\n{\n    switch (v)\n    {\n`;
      for (const v of values) out += `        case ${name}::${v}: return ${cppString(v)};\n`;
      out += `    }\n\n    return "";\n}\n`;
      out += `\ninline Json toJson (${name} v) { return toString (v); }\n`;
      out += `\ninline void readValue (Reader& r, const Json& j, ${name}& out)\n{\n    std::string s;\n    readValue (r, j, s);\n\n`;
      for (const v of values) out += `    if (s == ${cppString(v)}) { out = ${name}::${v}; return; }\n`;
      out += `\n    r.fail ("unknown value \\"" + s + "\\"");\n}\n`;
    }

    for (const name of this.order) {
      const kind = this.defKind(name);
      if (kind === "struct") out += this.generateStruct(name);
      if (kind === "union") out += this.generateUnion(name);
    }

    return out + `\n} // namespace gk::model\n`;
  }

  generateStruct(name: string): string {
    const def = this.defs[name];
    const props = Object.entries<Schema>(def.properties ?? {});
    let members = "";
    let reader = `    r.expectObject (j, { ${props.map(([p]) => cppString(p)).join(", ")} });\n\n`;
    let writer = `    auto j = Json::object();\n`;

    for (const [prop, s] of props) {
      const required = def.required?.includes(prop) ?? false;

      if (s.const !== undefined) {
        const constant = JSON.stringify(s.const);
        reader += `    r.required (j, ${cppString(prop)}, [&] (const Json& v) { r.checkConst (v, ${constant}); });\n`;
        writer += `    j[${cppString(prop)}] = ${constant};\n`;
        continue;
      }

      const r = this.resolve(s, name, prop);
      const optional = this.isOptional(def, prop, s);
      const field = `out.${prop}`;

      members += this.comment(s.description, "    ");
      members += optional
        ? `    std::optional<${r.cppType}> ${prop};\n`
        : `    ${r.cppType} ${prop}${this.memberDefault(r)};\n`;

      const target = optional ? `${field}.emplace()` : field;
      const checks = this.checks(r, optional ? `*${field}` : field);
      const body = [`readValue (r, v, ${target});`, ...checks].join(" ");
      reader += `    r.${required ? "required" : "optional"} (j, ${cppString(prop)}, [&] (const Json& v) { ${body} });\n`;

      writer += optional
        ? `\n    if (v.${prop})\n        j[${cppString(prop)}] = toJson (*v.${prop});\n\n`
        : `    j[${cppString(prop)}] = toJson (v.${prop});\n`;
    }

    writer = writer.replace(/\n\n\n/g, "\n\n").replace(/\n\n$/, "\n");

    return `\n${this.comment(def.description, "")}struct ${name}\n{\n${members}\n    bool operator== (const ${name}&) const = default;\n};\n`
      + `\ninline void readValue (Reader& r, const Json& j, ${name}& out)\n{\n${reader}}\n`
      + `\ninline Json toJson (const ${name}& v)\n{\n${writer}    return j;\n}\n`;
  }

  generateUnion(name: string): string {
    const def = this.defs[name];
    const tag = def.discriminator?.propertyName;
    if (!tag) throw new Error(`Union ${name} needs a discriminator`);
    const alternatives = def.oneOf.map((o: Schema) => {
      const alt = refName(o.$ref);
      const value = this.defs[alt].properties?.[tag]?.const;
      if (typeof value !== "string") throw new Error(`${alt} needs a const "${tag}"`);
      return { alt, value };
    });

    let out = `\n${this.comment(def.description, "")}using ${name} = std::variant<${alternatives.map((a: any) => a.alt).join(", ")}>;\n`;
    out += `\ninline void readValue (Reader& r, const Json& j, ${name}& out)\n{\n    if (! j.is_object())\n        r.fail ("expected object");\n\n`;
    out += `    std::string tag;\n    r.required (j, ${cppString(tag)}, [&] (const Json& v) { readValue (r, v, tag); });\n\n`;
    for (const { alt, value } of alternatives)
      out += `    if (tag == ${cppString(value)}) { readValue (r, j, out.emplace<${alt}>()); return; }\n`;
    out += `\n    r.fail ("unknown ${tag} \\"" + tag + "\\"");\n}\n`;
    out += `\ninline Json toJson (const ${name}& v)\n{\n    return std::visit ([] (auto& alt) { return toJson (alt); }, v);\n}\n`;
    return out;
  }
}

//==============================================================================
async function generateTypeScript(root: Schema, source: string): Promise<string> {
  return compile(structuredClone(root), root.title, {
    bannerComment: `// ${banner(source)}`,
    additionalProperties: false,
    unreachableDefinitions: true,
    style: { semi: true, singleQuote: false, printWidth: 120 },
  });
}

const check = process.argv.includes("--check");
let stale = false;

for (const target of targets) {
  const root = JSON.parse(readFileSync(join(schemaDir, target.schema), "utf8"));
  const outputs: [string, string][] = [
    [target.ts, await generateTypeScript(root, target.schema)],
    [target.cpp, new CppGenerator(root, target.schema).generate()],
  ];

  for (const [path, content] of outputs) {
    const file = join(schemaDir, path);
    const current = existsSync(file) ? readFileSync(file, "utf8") : "";

    if (current === content) continue;

    if (check) {
      console.error(`Out of date: ${path}`);
      stale = true;
    } else {
      writeFileSync(file, content);
      console.log(`Wrote ${path}`);
    }
  }
}

if (stale) {
  console.error("Run `pnpm codegen` and commit the result.");
  process.exit(1);
}
