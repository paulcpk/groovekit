class TsGenerator {
  readonly set: SchemaSet;
  readonly file: string;

  constructor(set: SchemaSet, file: string) {
    this.set = set;
    this.file = file;
  }

  type(r: Resolved): string {
    switch (r.kind) {
      case "array": return `${this.wrap(this.type(r.item!))}[]`;
      case "map": return `Record<string, ${this.type(r.item!)}>`;
      case "any": return r.name === "any" ? (r.schema.type === "object" ? "Record<string, unknown>" : "unknown") : r.name;
      case "primitive":
        if (this.set.defs.has(r.name)) return r.name;
        if (r.schema.type === "integer" && r.schema.enum) return r.schema.enum.join(" | ");
        return r.schema.type === "integer" ? "number" : r.schema.type;
      default: return r.name;
    }
  }

  wrap(t: string): string {
    return t.includes("|") ? `(${t})` : t;
  }

  generate(): string {
    const imports = new Map<string, Set<string>>();
    const order = this.set.ordered(this.file);

    for (const name of order)
      for (const dep of this.set.dependencies(name)) {
        const depFile = this.set.defs.get(dep)!.file;
        if (depFile === this.file) continue;
        const module = "./" + targets.find((t) => t.schema === depFile)!.ts.split("/").pop();
        if (!imports.has(module)) imports.set(module, new Set());
        imports.get(module)!.add(dep);
      }

    let out = `// ${banner(this.file)}\n\n`;
    for (const [module, names] of imports) out += `import type { ${[...names].sort().join(", ")} } from "${module}";\n`;
    if (imports.size) out += "\n";

    for (const [name, { file, values }] of this.set.enums)
      if (file === this.file) out += `export type ${name} = ${values.map(quote).join(" | ")};\n`;

    for (const name of order) {
      const def = this.set.def(name);
      const kind = this.set.kind(name);
      out += "\n" + comment(def.description, "", "ts");

      if (kind === "alias") out += `export type ${name} = ${def.type === "integer" ? "number" : def.type};\n`;
      if (kind === "any") out += `export type ${name} = ${def.type === "object" ? "Record<string, unknown>" : "unknown"};\n`;
      if (kind === "union") out += `export type ${name} = ${this.set.unionAlternatives(name).alternatives.map((a) => a.alt).join(" | ")};\n`;

      if (kind === "struct") {
        out += `export interface ${name} {\n`;
        for (const [prop, s] of Object.entries<Schema>(def.properties ?? {})) {
          const optional = !def.required?.includes(prop);
          out += comment(s.description, "  ", "ts");
          const type = s.const !== undefined ? JSON.stringify(s.const) : this.type(this.set.resolve(s, name, prop));
          out += `  ${prop}${optional ? "?" : ""}: ${type};\n`;
        }
        out += "}\n";
      }
    }

    return out;
  }
}

//==============================================================================
const set = new SchemaSet(targets.map((t) => t.schema));
const check = process.argv.includes("--check");
let stale = false;

for (const target of targets) {
  const outputs: [string, string][] = [
    [target.ts, new TsGenerator(set, target.schema).generate()],
    [target.cpp, new CppGenerator(set, target.schema).generate()],
  ];

  for (const [path, content] of outputs) {
    const file = join(schemaDir, path);
    const current = existsSync(file) ? readFileSync(file, "utf8") : "";

    if (current === content) continue;

    if (check) {
      console.error(`Out of date: ${path}`);
      stale = true;
    } else {
      writeFileSync(file, content);
      console.log(`Wrote ${path}`);
    }
  }
}

if (stale) {
  console.error("Run `pnpm codegen` and commit the result.");
  process.exit(1);
}
