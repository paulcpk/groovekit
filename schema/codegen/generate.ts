class CppGenerator {
  readonly set: SchemaSet;
  readonly file: string;

  constructor(set: SchemaSet, file: string) {
    this.set = set;
    this.file = file;
  }

  primitive(s: Schema): string {
    switch (s.type) {
      case "string": return "std::string";
      case "boolean": return "bool";
      case "number": return "double";
      case "integer": return s.maximum === undefined && !s.enum ? "int64_t" : "int";
    }
    throw new Error(`Unsupported primitive ${JSON.stringify(s)}`);
  }

  type(r: Resolved): string {
    switch (r.kind) {
      case "array": return `std::vector<${this.type(r.item!)}>`;
      case "map": return `std::map<std::string, ${this.type(r.item!)}>`;
      case "any": return r.name === "any" ? "Json" : r.name;
      case "primitive": return r.schema.$ref || this.set.defs.has(r.name) ? r.name : this.primitive(r.schema);
      default: return r.name;
    }
  }

  memberDefault(r: Resolved): string {
    const d = r.schema.default;
    if (d === undefined) return r.kind === "primitive" && r.schema.type !== "string" ? " {}" : "";
    if (r.kind === "enum") return ` = ${r.name}::${d}`;
    if (typeof d === "object" && d !== null) {
      if (Object.keys(d).length > 0) throw new Error("Only empty array/object defaults are supported");
      return "";
    }
    if (typeof d === "string") return ` = ${quote(d)}`;
    return ` = ${d}`;
  }

  checks(r: Resolved, expr: string): string[] {
    const s = r.schema;
    const out: string[] = [];
    if (r.kind === "primitive") {
      if (s.type === "integer" && s.enum) out.push(`r.checkOneOf (${expr}, { ${s.enum.join(", ")} });`);
      if (s.minimum !== undefined) out.push(`r.checkMin (${expr}, ${s.minimum});`);
      if (s.maximum !== undefined) out.push(`r.checkMax (${expr}, ${s.maximum});`);
      if (s.minLength !== undefined) out.push(`r.checkMinLength (${expr}, ${s.minLength});`);
      if (s.pattern !== undefined) out.push(`r.checkPattern (${expr}, ${quote(s.pattern)});`);
    }
    if (r.kind === "array" && s.minItems !== undefined) out.push(`r.checkMinItems (${expr}, ${s.minItems});`);
    return out;
  }

  generate(): string {
    const includes = new Set<string>();
    for (const target of targets)
      if (target.schema !== this.file && this.usesFile(target.schema))
        includes.add(target.cpp.split("/").pop()!);

    let out = `// ${banner(this.file)}\n\n#pragma once\n\n`;
    out += includes.size ? [...includes].map((i) => `#include "${i}"\n`).join("") : `#include "JsonIO.h"\n`;
    out += `\n#include <variant>\n\nnamespace gk::model\n{\n\n`;

    const order = this.set.ordered(this.file);

    for (const name of order) {
      const kind = this.set.kind(name);
      if (kind === "alias") out += `${comment(this.set.def(name).description, "", "cpp")}using ${name} = ${this.primitive(this.set.def(name))};\n`;
      if (kind === "any") out += `${comment(this.set.def(name).description, "", "cpp")}using ${name} = Json;\n`;
    }

    for (const [name, { file, values }] of this.set.enums) {
      if (file !== this.file) continue;
      out += `\nenum class ${name}\n{\n${values.map((v) => `    ${v}`).join(",\n")}\n};\n`;
      out += `\ninline const char* toString (${name} v)\n{\n    switch (v)\n    {\n`;
      for (const v of values) out += `        case ${name}::${v}: return ${quote(v)};\n`;
      out += `    }\n\n    return "";\n}\n`;
      out += `\ninline Json toJson (${name} v) { return toString (v); }\n`;
      out += `\ninline void readValue (Reader& r, const Json& j, ${name}& out)\n{\n    std::string s;\n    readValue (r, j, s);\n\n`;
      for (const v of values) out += `    if (s == ${quote(v)}) { out = ${name}::${v}; return; }\n`;
      out += `\n    r.fail ("unknown value \\"" + s + "\\"");\n}\n`;
    }

    for (const name of order) {
      const kind = this.set.kind(name);
      if (kind === "struct") out += this.struct(name);
      if (kind === "union") out += this.union(name);
    }

    return out + `\n} // namespace gk::model\n`;
  }

  usesFile(file: string): boolean {
    return this.set.ordered(this.file).some((name) => this.set.dependencies(name).some((d) => this.set.defs.get(d)!.file === file));
  }

  struct(name: string): string {
    const def = this.set.def(name);
    const props = Object.entries<Schema>(def.properties ?? {});
    let members = "";
    let reader = `    r.expectObject (j, { ${props.map(([p]) => quote(p)).join(", ")} });\n\n`;
    let writer = `    auto j = Json::object();\n`;

    for (const [prop, s] of props) {
      const required = def.required?.includes(prop) ?? false;

      if (s.const !== undefined) {
        const constant = JSON.stringify(s.const);
        reader += `    r.required (j, ${quote(prop)}, [&] (const Json& v) { r.checkConst (v, ${constant}); });\n`;
        writer += `    j[${quote(prop)}] = ${constant};\n`;
        continue;
      }

      const r = this.set.resolve(s, name, prop);
      const type = this.type(r);
      const optional = this.set.isOptional(def, prop, s);
      const field = `out.${prop}`;

      members += comment(s.description, "    ", "cpp");
      members += optional ? `    std::optional<${type}> ${prop};\n` : `    ${type} ${prop}${this.memberDefault(r)};\n`;

      const target = optional ? `${field}.emplace()` : field;
      const body = [`readValue (r, v, ${target});`, ...this.checks(r, optional ? `*${field}` : field)].join(" ");
      reader += `    r.${required ? "required" : "optional"} (j, ${quote(prop)}, [&] (const Json& v) { ${body} });\n`;

      writer += optional
        ? `\n    if (v.${prop})\n        j[${quote(prop)}] = toJson (*v.${prop});\n\n`
        : `    j[${quote(prop)}] = toJson (v.${prop});\n`;
    }

    writer = writer.replace(/\n\n\n/g, "\n\n").replace(/\n\n$/, "\n");

    return (
      `\n${comment(def.description, "", "cpp")}struct ${name}\n{\n${members}\n    bool operator== (const ${name}&) const = default;\n};\n` +
      `\ninline void readValue (Reader& r, const Json& j, ${name}& out)\n{\n${reader}}\n` +
      `\ninline Json toJson (const ${name}& v)\n{\n${writer}    return j;\n}\n`
    );
  }

  union(name: string): string {
    const def = this.set.def(name);
    const { tag, alternatives } = this.set.unionAlternatives(name);

    let out = `\n${comment(def.description, "", "cpp")}using ${name} = std::variant<${alternatives.map((a) => a.alt).join(", ")}>;\n`;
    out += `\ninline void readValue (Reader& r, const Json& j, ${name}& out)\n{\n    if (! j.is_object())\n        r.fail ("expected object");\n\n`;
    out += `    std::string tag;\n    r.required (j, ${quote(tag)}, [&] (const Json& v) { readValue (r, v, tag); });\n\n`;
    for (const { alt, value } of alternatives)
      out += `    if (tag == ${quote(value)}) { readValue (r, j, out.emplace<${alt}>()); return; }\n`;
    out += `\n    r.fail ("unknown ${tag} \\"" + tag + "\\"");\n}\n`;
    out += `\ninline Json toJson (const ${name}& v)\n{\n    return std::visit ([] (auto& alt) { return toJson (alt); }, v);\n}\n`;
    return out;
  }
}

